# ───────────────────────── STAR_TAIL：星号分节符的尾部特例 ─────────────────────────
# 🔴 只认 ASCII 星号与全角星号：× 在正文里用作人名/地名打码（「×××」），不删
STAR_LINE = re.compile(r"^\s*[*＊]{4,}\s*$")
# 星号开头的行（星号后允许挂一小截话术）：捕获组 rest = 星号之后的剩余内容
STAR_LINE_LEAD = re.compile(r"^\s*[*＊]{4,}[  \t]*(?P<rest>.*)$")
# 行首星号串（>=1 个）：只用于 PURE_LINE 的「剥掉分隔线再匹配」重试
STAR_PREFIX = re.compile(r"^\s*[*＊]+[  \t]*(?P<rest>.*)$")
# 求票/作者话术关键词：星号行之后出现这些词才认定是「作者话块」
PLEA_KEYWORDS = re.compile(
    r"月票|推荐票|投票|收藏|订阅|打赏|点赞|首订|盟主|加更|求票|拉票|冲榜|双倍|"
    r"支持(作者|小莫|番茄|老牛|本书|我)|正版|感谢|谢谢|书评|章说|推荐|点收|一个都不能少"
)
STAR_TAIL_WINDOW = 200      # 星号行后 200 字内必须命中话术词（用户给定口径）
STAR_TAIL_MIN_BODY = 200    # 星号行之前至少还有 200 个汉字正文，防止整章只有星号
STAR_TAIL_SHORT_MAX_CJK = 40   # 星号行自身挂的尾巴最多 40 汉字；更长说明这行有正文内容，不碰


def match_star_line(line: str) -> str | None:
    """行首是 >=4 个星号 → 返回星号之后的剩余内容（可能为空串）；否则 None。"""
    m = STAR_LINE_LEAD.match(line)
    return None if not m else m.group("rest").strip()

