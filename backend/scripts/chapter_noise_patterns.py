def classify_pure_line(line: str) -> str | None:
    """返回该行命中的 PURE_LINE 模式名，没命中返回 None。

    两次尝试：整行匹配；以及剥掉行首星号分隔线后再匹配——`******(未完待续。…投推荐票、月票…)`
    这种「分隔线 + 站点尾标」同处一行，不剥星号就 fullmatch 不上，会让尾标残留。
    """
    s = line.strip()
    if not s:
        return None
    candidates: list[str] = [s]
    m = STAR_PREFIX.match(s)
    if m and m.group("rest").strip():
        candidates.append(m.group("rest").strip())
    for cand in candidates:
        for name, rx in PURE_LINE:
            if rx.fullmatch(cand):
                return name
    return None


def apply_inline(line: str) -> tuple[str, list[str]]:
    """删掉行内的噪声片段，返回 (新行, 命中的模式名列表，每次命中一个元素)。"""
    hit: list[str] = []
    out = line
    for name, rx in INLINE:
        new, n = rx.subn("", out)
        if n:
            hit.extend([name] * n)
            out = new
    return out, hit
